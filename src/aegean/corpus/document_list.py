"""Build the canonical document list (A1.6).

  python -m aegean.corpus.document_list

Writes data/processed/document-list/document-list.tsv (one row per document,
keyed by GORILA siglum) and MANIFEST.json (input hashes, rule parameters,
counts, code commit). Inputs must be present and must match their pinned
hashes: run the three fetch/verify scripts first (data/raw/*/fetch.py).

The list contains document IDs and metadata derived in part from SigLA, so it
carries SigLA's licence, CC BY-NC-SA 4.0 (README.md in the output folder).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from pathlib import Path

from aegean.corpus import concordance, inclusion

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "data/processed/document-list"
PINNED = {
    "lineara.xyz": "9a14cc300201ac8ed07563c09b92142ab59de91a74e646b2e743ca6aeb695f5e",
    "sigla": "0c4ef69f5de4cc3d9382cca782c1cf47e2ca1be40696bcfc8e97514f9b0781dd",
    "younger": "05305bc5235db0b0ebae1a828a46dcc35c0f004fb9a9a50ca522695a82907201",
}
COLUMNS = ["key", "aliases", "site", "series", "support", "register", "off_crete", "lost", "tier",
           "n_sources", "sources", "source_ids", "max_signs", "max_numerals", "flags",
           "listed", "analysis_default", "exclusion_reasons"]
LICENCE = """# Canonical Linear A document list (A1.6)

Generated by `python -m aegean.corpus.document_list`; never edit by hand (CLAUDE.md).

**Licence: CC BY-NC-SA 4.0.** The list is derived in part from SigLA (© Ester Salgarella & Simon Castellan, https://sigla.phis.me, CC BY-NC-SA 4.0), so the same terms apply. Other inputs: lineara.xyz (no licence stated), Younger 2024 (no licence stated). This file holds only document identifiers and counts, not their texts.

The rules and their status: `docs/inclusion-rules.md`. Inputs, rule parameters and counts: `MANIFEST.json`.
"""


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _row(c: concordance.DocCluster, d: inclusion.Decision) -> list[str]:
    ids = sorted({f"{r.source}:{r.source_id}" for r in c.records})
    return [c.key, ";".join(c.aliases), c.site, c.series or "", c.support, c.register,
            str(c.off_crete).lower(), str(c.lost).lower(), d.tier, str(len(c.sources)),
            ";".join(c.sources), ";".join(ids), str(c.max_signs), str(c.max_numerals),
            ";".join(c.flags), str(d.listed).lower(), str(d.analysis_default).lower(), ";".join(d.reasons)]


def build(out: Path = OUT, rules: inclusion.Rules = inclusion.Rules()) -> dict:
    for src, path in concordance.INPUTS.items():
        if not path.exists():
            raise SystemExit(f"missing input {path}; see data/raw/{src.replace('.xyz', '.xyz')}/")
        if sha256(path) != PINNED[src]:
            raise SystemExit(f"HASH MISMATCH for {path}")
    clusters, unmatched = concordance.build()
    if unmatched:
        raise SystemExit(f"{len(unmatched)} unmatched source IDs; add them to data/concordance/aliases.tsv")
    decisions = [inclusion.decide(c, rules) for c in clusters]
    out.mkdir(parents=True, exist_ok=True)
    tsv = out / "document-list.tsv"
    lines = ["\t".join(COLUMNS)] + ["\t".join(_row(c, d)) for c, d in zip(clusters, decisions) if d.listed]
    tsv.write_text("\n".join(lines) + "\n", encoding="utf-8")
    (out / "README.md").write_text(LICENCE, encoding="utf-8")
    try:
        commit = subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"], capture_output=True,
                                text=True, check=True).stdout.strip()
    except Exception:  # noqa: BLE001 - not a git checkout
        commit = "unknown"
    manifest = {
        "task": "A1.6",
        "status": "DECIDED 2026-11-10 (Marius: R3/R4 T1 only, R7 keep single-source, R9 keep <n> out; R5/R6/R8/R10 proposed defaults kept). See docs/inclusion-rules.md",
        "code_commit_at_build": commit,
        "inputs": {s: {"path": str(p.relative_to(REPO)), "sha256": PINNED[s]} for s, p in concordance.INPUTS.items()},
        "aliases_sha256": sha256(concordance.ALIASES),
        "output_sha256": sha256(tsv),
        **inclusion.summarise(clusters, rules),
    }
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return manifest


def main() -> None:
    argparse.ArgumentParser(description=__doc__).parse_args()
    m = build()
    print(json.dumps({k: m[k] for k in ("documents", "listed", "analysis_default", "by_tier")}, indent=1))


if __name__ == "__main__":
    main()
