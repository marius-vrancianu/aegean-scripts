"""Freeze the held-out split (A1.12; plan §0.4, §0.7).

  python -m aegean.corpus.split            # draw once, write data/heldout.txt; (re)write the release manifest
  python -m aegean.corpus.split --check    # verify that data/heldout.txt equals a fresh draw

The split is a pure function of (document list, SEED, FRACTION, MIN_STRATUM):

1. Population: the documents with `analysis_default = true` in the canonical
   document list (568 at corpus-v1.0).
2. Stratum: (site, support), both as given in the document list.
3. A stratum with fewer than MIN_STRATUM documents goes wholly to training.
4. Quota: every other stratum gives FRACTION of its documents. Quotas are
   whole numbers: each stratum first gets floor(FRACTION * n); the documents
   still missing from round(FRACTION * eligible total) go one each to the
   strata with the largest fractional parts (ties: stratum name order).
5. Draw: inside a stratum, documents are ordered by
   sha256("<SEED>|<document key>") and the first `quota` are held out.

Step 5 uses a hash instead of a random-number generator so that the draw does
not depend on a Python version or platform, and so that anyone can check one
document by hand. No step reads a document's text.

The seed was published in the pull request description before the first draw
(PR for A1.12). Changing SEED, FRACTION or MIN_STRATUM after the freeze is a
change to the held-out policy: it needs Marius's instruction and an independent
review (CLAUDE.md -> Merging). The split is never redrawn (plan §0.4).
"""
from __future__ import annotations

import argparse
import collections
import csv
import hashlib
import json
import math
import sys
from fractions import Fraction
from pathlib import Path

from aegean.corpus.heldout import HELDOUT_FILE, SPLIT_SOURCE, load_split

REPO = Path(__file__).resolve().parents[3]
DOCUMENT_LIST = REPO / "data/processed/document-list/document-list.tsv"
RELEASE = "corpus-v1.0"
RELEASE_DIR = REPO / "data/processed" / RELEASE
LAYERS_MANIFEST = REPO / "data/processed/corpus-v1.0-pre/MANIFEST.json"

SEED = 20261111  # the date of the freeze; fixed in the PR description before drawing
FRACTION = Fraction(1, 5)
MIN_STRATUM = 5

BEGIN = "# >>> frozen split (generated by aegean.corpus.split; do not edit) >>>"
END = "# <<< frozen split <<<"

Stratum = tuple[str, str]


def read_population(path: Path = DOCUMENT_LIST) -> list[dict]:
    """Rows of the default analysis set, in file order."""
    with path.open(encoding="utf-8", newline="") as f:
        return [r for r in csv.DictReader(f, delimiter="\t") if r["analysis_default"] == "true"]


def stratum_of(row: dict) -> Stratum:
    return (row["site"], row["support"])


def quotas(sizes: dict[Stratum, int], fraction: Fraction = FRACTION,
           min_stratum: int = MIN_STRATUM) -> dict[Stratum, int]:
    """Held-out documents per stratum (0 for strata below `min_stratum`). Exact arithmetic."""
    eligible = {s: n for s, n in sizes.items() if n >= min_stratum}
    exact = {s: fraction * n for s, n in eligible.items()}
    out = {s: math.floor(q) for s, q in exact.items()}
    total = sum(eligible.values()) * fraction
    target = math.floor(total + Fraction(1, 2))  # round half up
    by_remainder = sorted(eligible, key=lambda s: (-(exact[s] - out[s]), s))
    for s in by_remainder[: target - sum(out.values())]:
        out[s] += 1
    return {s: out.get(s, 0) for s in sizes}


def rank(seed: int, key: str) -> str:
    return hashlib.sha256(f"{seed}|{key}".encode("utf-8")).hexdigest()


def draw(rows: list[dict], seed: int = SEED, fraction: Fraction = FRACTION,
         min_stratum: int = MIN_STRATUM) -> tuple[list[str], dict[Stratum, dict]]:
    """(sorted held-out keys, per-stratum table)."""
    members: dict[Stratum, list[str]] = collections.defaultdict(list)
    for r in rows:
        members[stratum_of(r)].append(r["key"])
    keys = [k for ks in members.values() for k in ks]
    if len(keys) != len(set(keys)):
        raise ValueError("duplicate document keys in the population")
    q = quotas({s: len(ks) for s, ks in members.items()}, fraction, min_stratum)
    held: list[str] = []
    table = {}
    for s in sorted(members):
        ordered = sorted(members[s], key=lambda k: (rank(seed, k), k))
        held += ordered[: q[s]]
        table[s] = {"documents": len(ordered), "heldout": q[s], "training": len(ordered) - q[s],
                    "split": len(ordered) >= min_stratum}
    return sorted(held), table


def render(text: str, held: list[str]) -> str:
    """data/heldout.txt with the generated block replaced (or appended)."""
    block = [BEGIN,
             f"# {len(held)} documents; seed {SEED}, fraction {FRACTION}, strata below {MIN_STRATUM} "
             "documents kept in training.",
             "# Keys are canonical document keys (data/processed/document-list/document-list.tsv).",
             "# These documents stay in the corpus files; aegean.corpus.load withholds them unless a",
             "# frozen confirmatory hypothesis is named. Policy: CLAUDE.md, plan §0.4, docs/heldout-split.md.",
             *[f"{SPLIT_SOURCE}:{k}" for k in held], END]
    lines = text.rstrip("\n").split("\n")
    if BEGIN in lines:
        i, j = lines.index(BEGIN), lines.index(END)
        lines[i: j + 1] = block
    else:
        lines += ["", *block]
    return "\n".join(lines) + "\n"


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def manifest(rows: list[dict], held: list[str], table: dict[Stratum, dict]) -> dict:
    layers = json.loads(LAYERS_MANIFEST.read_text(encoding="utf-8"))
    kept_whole = {s: t for s, t in table.items() if not t["split"]}
    return {
        "release": RELEASE,
        "task": "A1.12",
        "components": {
            "document_list": {"path": str(DOCUMENT_LIST.relative_to(REPO)), "sha256": sha256(DOCUMENT_LIST)},
            "witnesses": {"path": "data/processed/corpus-v1.0-pre/witnesses.jsonl (gitignored; rebuild with "
                                  "python -m aegean.corpus.build_layers)",
                          "sha256": layers["output_sha256"], "schema_version": layers["schema_version"],
                          "inputs": layers["inputs"]},
            "heldout": {"path": str(HELDOUT_FILE.relative_to(REPO)), "sha256": sha256(HELDOUT_FILE)},
        },
        "split": {
            "seed": SEED,
            "fraction": str(FRACTION),
            "min_stratum": MIN_STRATUM,
            "stratified_by": ["site", "support"],
            "method": "per stratum: order keys by sha256('<seed>|<key>'), hold out the first <quota>; "
                      "quotas by largest remainder (see aegean.corpus.split)",
            "population": len(rows),
            "eligible_documents": sum(t["documents"] for t in table.values() if t["split"]),
            "heldout": len(held),
            "training": len(rows) - len(held),
            "strata": len(table),
            "strata_split": sum(t["split"] for t in table.values()),
            "strata_kept_in_training": len(kept_whole),
            "documents_in_strata_kept_in_training": sum(t["documents"] for t in kept_whole.values()),
            "heldout_keys_sha256": hashlib.sha256("\n".join(held).encode("utf-8")).hexdigest(),
            "by_stratum": [{"site": s[0], "support": s[1], **t} for s, t in sorted(table.items())],
        },
        "blindness": "Blind only for hypotheses registered after the freeze. A1.6-A1.9 and A2 processed every "
                     "document; nothing from A2 can be confirmed on this split. See docs/corpus-changelog.md.",
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify data/heldout.txt against a fresh draw; write nothing")
    args = ap.parse_args(argv)
    rows = read_population()
    held, table = draw(rows)
    if args.check:
        frozen = sorted(load_split())
        if frozen != held:
            print(f"MISMATCH: data/heldout.txt has {len(frozen)} split documents, a fresh draw gives {len(held)} "
                  f"({len(set(frozen) ^ set(held))} differ)", file=sys.stderr)
            return 1
        print(f"OK: {len(held)} held-out documents reproduce from seed {SEED}")
        return 0
    frozen = sorted(load_split())
    if not frozen:
        HELDOUT_FILE.write_text(render(HELDOUT_FILE.read_text(encoding="utf-8"), held), encoding="utf-8")
    elif frozen != held:
        print("data/heldout.txt already holds a different frozen split; it is never redrawn (plan §0.4).",
              file=sys.stderr)
        return 1
    RELEASE_DIR.mkdir(parents=True, exist_ok=True)
    m = manifest(rows, held, table)
    (RELEASE_DIR / "MANIFEST.json").write_text(json.dumps(m, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps({k: m["split"][k] for k in ("seed", "population", "eligible_documents", "heldout", "training",
                                                 "strata_split", "strata_kept_in_training")}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
